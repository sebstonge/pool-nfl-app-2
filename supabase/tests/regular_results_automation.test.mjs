test('manual closure requires fresh proof, silently corrects existing scores and determines the next order atomically',embedded, async()=>{
  await withEmbedded(async sql=>{
    const f=await setup(sql);
    const qbGame=score(f.qbGame,17,10,'5005');
    const firstRatings=[rating(f.washington,f.qbGame,100,'Current QB','99'),rating(f.buffalo,f.qbGame,90,'Bills QB','123')];
    await commit(sql,await state(sql),{games:[score(f.poolGame,21,14,'5010'),qbGame],ratings:firstRatings});
    assert.deepEqual(order((await business(sql)).scores),[other,member]);
    const oldEvents=await events(sql,'rankings_updated');
    const qbEvents=await events(sql,'qb_final');
    const fresh=await state(sql);
    const changes={mode:'close',games:[score(f.poolGame,14,21,'5010'),qbGame],
      ratings:[rating(f.washington,f.qbGame,86,'Replacement QB','101'),rating(f.buffalo,f.qbGame,150,'Bills QB','123')]};

    await checkSame(sql,()=>commit(sql,fresh,{...changes,ratings:changes.ratings.slice(0,1)}),/preuves ESPN finales incomplètes/i);
    await checkSame(sql,()=>commit(sql,fresh,{...changes,games:[qbGame]}),/preuves ESPN finales incomplètes/i);
    await checkSame(sql,()=>commit(sql,fresh,{...changes,ratings:[{...changes.ratings[0],game_id:f.poolGame},changes.ratings[1]]}),/Invalid ESPN FINAL QB evidence/);
    await sql("update games set home_score=0 where external_game_id='6010'");
    await checkSame(sql,()=>commit(sql,fresh,changes),/Admissible unstarted next regular week required/);
    await sql("update games set home_score=null where external_game_id='6010'");

    const outcome=await commit(sql,fresh,changes);
    assert.equal(outcome.advance.week,6);
    assert.equal(outcome.advance.revision,fresh.settings.revision+1);
    assert.equal(outcome.changed,true);
    assert.equal(outcome.qb_events_queued,0);
    assert.deepEqual(await events(sql,'rankings_updated'),oldEvents);
    assert.deepEqual(await events(sql,'qb_final'),qbEvents);
    const after=await business(sql);
    assert.deepEqual(order(after.scores),[member,other]);
    assert.equal(after.scores.find(row=>row.user_id===other).final_score,3);
    assert.equal(after.week.qb_ratings.find(row=>row.qb_id===f.washington).actual_espn_athlete_id,'101');
    assert.deepEqual(after.week.qb_picks,fresh.qb_picks);
    assert.equal(after.clocks.filter(row=>row.week===6).length,1);
    await checkSame(sql,()=>commit(sql,fresh,changes),/Stale, closed or paused regular context/);
  });
});

test('manual stats are shared, automatic stats avoid rewriting an existing athlete, and a failed calculation rolls all writes back',embedded,async()=>{
  await withEmbedded(async sql=>{
    const f=await setup(sql);
    const bowl={id:f.team,wins:2,losses:0,ties:0,division_rank:1,division_name:'NFC Test'};
    const row={week:5,espn_athlete_id:'99',qb_name:'Current QB',team:'Washington Commanders',passer_rating:91};
    const changes={games:[score(f.poolGame,21,14,'5010')],qbStats:[row],teams:[bowl]};
    const before=await state(sql);
    await checkSame(sql,()=>commit(sql,before,{...changes,results:[]}),/Weekly recalculation mismatch/);
    const auto=await commit(sql,before,changes);
    assert.equal(auto.qb_stats_updated,1);
    assert.equal(auto.teams_updated,1);
    const stateAfter=await state(sql);
    const prior=(await business(sql)).qb_stats;
    const correction={...changes,qbStats:[{...row,passer_rating:123}]};
    const frozen=await commit(sql,stateAfter,correction);
    assert.equal(frozen.qb_stats_updated,0);
    assert.deepEqual((await business(sql)).qb_stats,prior);
    const manual=await commit(sql,stateAfter,{...correction,mode:'manual'});
    assert.equal(manual.qb_stats_updated,1);
    assert.equal((await business(sql)).qb_stats[0].passer_rating,123);
  });
});

async function waitForSession(sql,label,condition) {
  for(let tries=0;tries<100;tries++) {
    const waiting=await sql(`select exists(select 1 from pg_stat_activity where application_name=${quoteSql(label)} and ${condition});`);
    if (waiting==='t') return;
    await wait(20);
  }
  assert.fail('Native session did not enter expected state: '+label);
}

test('two native database sessions serialize the cron with a manual close and reject the stale writer',native,async()=>{
  await withNativeQbFixture(async db=>{
    const {sql,startSql}=db;
    const f=await setup(sql);
    const old=await state(sql);
    const games=[score(f.poolGame,21,14,'5010'),score(f.qbGame,17,10,'5005')];
    const ratings=[rating(f.washington,f.qbGame,100,'Current QB','99'),rating(f.buffalo,f.qbGame,90,'Bills QB','123')];
    const close=startSql(`set application_name='regular_close_first'; begin; set role service_role;
      ${commitSql(old,{mode:'close',games,ratings})} select pg_sleep(3); commit;`).done;
    await waitForSession(sql,'regular_close_first',"wait_event='PgSleep'");
    const concurrent=assert.rejects(startSql(`set application_name='regular_waiting_cron'; set role service_role;
      ${commitSql(old,{games,ratings})}`).done,/Stale, closed or paused regular context/);
    await waitForSession(sql,'regular_waiting_cron',"wait_event_type='Lock'");
    assert.equal(JSON.parse(await close).advance.week,6);
    await concurrent;
    const after=await business(sql);
    assert.equal(after.week.settings.current_week,6);
    assert.equal(after.clocks.filter(row=>row.week===6).length,1);
    assert.equal((await events(sql,'rankings_updated')).length,0);
    assert.equal((await events(sql,'qb_final')).length,2);
  });
});
