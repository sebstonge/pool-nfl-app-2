const state = sql => queryJson(sql,'select public.regular_week_ranking_state(2026,5);');
const events = (sql,type) => queryJson(sql,`select coalesce(jsonb_agg(to_jsonb(t) order by event_key),'[]') from public.push_notification_events t
 where notification_type=${quoteSql(type)};`);
const score = (id,home_score,away_score,external_game_id) => ({id,home_score,away_score,external_game_id,result_status:'final'});
const rating = (qb_id,game_id,passer_rating,actual_qb_name,actual_espn_athlete_id) =>
  ({qb_id,game_id,passer_rating,actual_qb_name,actual_espn_athlete_id});

function commitSql(expected,{mode='automatic',actor=mode==='manual'||mode==='close'?admin:null,games=[],ratings=[],teams=[],qbStats=[],results}={}) {
  if (results === undefined && mode !== 'qb-only') {
    const automatic = mode === 'automatic';
    const priorRatings = new Map(expected.qb_ratings.map(row=>[row.qb_id,row]));
    for (const proposed of ratings) {
      const current = priorRatings.get(proposed.qb_id);
      const frozen = automatic && current && current.passer_rating != null && current.actual_qb_name && current.actual_espn_athlete_id;
      if (!frozen) priorRatings.set(proposed.qb_id,proposed);
    }
    results = calculateRegularWeek({...expected,games:expected.games.map(game => {
      const proposed = games.find(item=>item.id===game.id);
      return !proposed || (automatic && game.result_status==='final') ? game : {...game,...proposed,result_status:'final'};
    }),qb_ratings:[...priorRatings.values()]});
  }
  return `select public.commit_regular_week_results(2026,5,${expected.settings.revision},${actor?quoteSql(actor):'null'},
    ${quoteSql(mode)},${quoteJson(expected)},${quoteJson(games)},${quoteJson(ratings)},${results===undefined?'null':quoteJson(results)},
    '2026-01-01T13:00:00Z',${quoteJson(qbStats)},${quoteJson(teams)});`;
}

const commit = (sql,expected,changes) => queryJson(sql,'set role service_role; '+commitSql(expected,changes));

async function checkSame(sql, command, pattern) {
  const before = await business(sql);
  await assert.rejects(command,pattern);
  assert.deepEqual(await business(sql),before);
}

test('weekly result transaction records first proven results, retries missing data, freezes corrections and deduplicates',embedded, async()=>{
  await withEmbedded(async sql=>{
    const f = await setup(sql);
    const before = await state(sql);
    const missing = await commit(sql,before);
    assert.equal(missing.games_updated,0);
    assert.equal(missing.ratings_updated,0);
    assert.deepEqual((await business(sql)).scores,[]);
    const initialGame = await commit(sql,await state(sql),{games:[score(f.poolGame,21,14,'5010')]});
    assert.equal(initialGame.games_updated,1);
    assert.equal(initialGame.version,1);
    assert.deepEqual(order((await business(sql)).scores),[other,member]);
    // A UI-known FINAL with no boxscore still does not create a fake rating.
    await checkSame(sql,()=>commit(sql,before,{games:[score(f.poolGame,21,14,'5010')]}),/Stale weekly ranking source/);

    const games = [score(f.qbGame,17,10,'5005')];
    const ratings = [rating(f.washington,f.qbGame,112.85,'Current QB','99'),rating(f.buffalo,f.qbGame,0,'Bills QB','123')];
    const beforeRating = await state(sql);
    await checkSame(sql,()=>commit(sql,beforeRating,{games,ratings:[],results:[]}),/Rating QB final attendu mais indisponible/);
    await checkSame(sql,()=>commit(sql,beforeRating,{games:[{...games[0],external_game_id:'5010'}],ratings}),/Invalid ESPN FINAL game evidence/);
    await checkSame(sql,()=>commit(sql,beforeRating,{games:[{...games[0],result_status:null}],ratings}),/Invalid ESPN FINAL game evidence/);
    const updated = await commit(sql,beforeRating,{games,ratings});
    assert.equal(updated.ratings_updated,2);
    assert.equal(updated.games_updated,1);
    assert.equal(updated.qb_events_queued,2);
    assert.equal(updated.version,2,'non-pool game changed the ranking with a rating');
    const sports = await business(sql);
    assert.equal(sports.scores.find(row=>row.user_id===member).final_score,2.257);
    assert.equal(sports.scores.find(row=>row.user_id===other).multiplier,1,'numeric zero keeps existing multiplier');
    const qbEvents = await events(sql,'qb_final');
    assert.deepEqual(qbEvents.map(row=>row.event_key),[eventKey(member),eventKey(other)]);
    assert.deepEqual(qbEvents[0].qb_final_payload,{actualQbName:'Current QB',opponent:'Buffalo Bills',passerRating:112.85});
    assert.equal(qbEvents[0].qb_final_attempted_at,null);
    assert.equal((await events(sql,'rankings_updated')).length,4);
    await checkSame(sql,()=>commit(sql,beforeRating,{games,ratings}),/Stale weekly ranking source/);
    const lateScore = score(f.poolGame,14,21,'5010');
    const lateRating = rating(f.washington,f.qbGame,88.4,'Later QB','101');
    const duplicate = await commit(sql,await state(sql),{games:[lateScore,...games],ratings:[lateRating,...ratings.slice(1)]});
    assert.equal(duplicate.games_updated,0);
    assert.equal(duplicate.ratings_updated,0);
    assert.equal(duplicate.qb_events_queued,0);
    assert.equal(duplicate.changed,false);
    assert.deepEqual(await business(sql),sports);
    assert.deepEqual(await events(sql,'qb_final'),qbEvents);
  });
});

test('authorized QB-only maintenance leaves scores intact and never reuses a legacy reservation',embedded, async()=>{
  await withEmbedded(async sql=>{
    const f=await setup(sql);
    const before=await state(sql);
    const changes={mode:'qb-only',games:[score(f.qbGame,17,10,'5005')],
      ratings:[rating(f.washington,f.qbGame,95,'Current QB','99'),rating(f.buffalo,f.qbGame,90,'Bills QB','123')]};
    await assert.rejects(sql('set role authenticated; '+commitSql(before,changes)),/permission denied/);
    await checkSame(sql,()=>commit(sql,before,{...changes,actor:admin}),/cannot impersonate/);
    await checkSame(sql,()=>commit(sql,before,{mode:'manual',actor:member}),/Administrator required/);
    await sql(`insert into public.push_notification_events(event_key,user_id,notification_type,week,season,status)
      values('${eventKey(member)}','${member}','qb_final',5,2026,'pending');`);

    const outcome=await commit(sql,before,changes);
    assert.equal(outcome.games_updated,0);
    assert.equal(outcome.ratings_updated,2);
    assert.equal(outcome.qb_events_queued,1);
    assert.deepEqual((await state(sql)).games,before.games);
    assert.deepEqual((await business(sql)).scores,[]);
    assert.equal((await events(sql,'rankings_updated')).length,0);
    let rows=await events(sql,'qb_final');
    assert.equal(rows[0].qb_final_payload,null,'legacy pending row stays untouched');
    assert.equal(rows[1].qb_final_payload.actualQbName,'Bills QB');
    await sql(`update public.push_notification_events set qb_final_attempted_at=clock_timestamp()
      where event_key='${eventKey(other)}';`);
    await assert.rejects(sql(`update public.push_notification_events set qb_final_attempted_at=null
      where event_key='${eventKey(other)}';`),/claim cannot be reset/);
    await assert.rejects(sql(`update public.push_notification_events set qb_final_payload='{}'
      where event_key='${eventKey(other)}';`),/payload is immutable/);
    rows=await events(sql,'qb_final');
    assert.ok(rows[1].qb_final_attempted_at);
    const duplicate=await commit(sql,await state(sql),changes);
    assert.equal(duplicate.qb_events_queued,0);
  });
});

