async function withEmbedded(task) {
  const url = pathToFileURL(process.env.PGLITE_MODULE);
  const {PGlite} = await import(url.href);
  const {pgcrypto} = await import(new URL('contrib/pgcrypto.js', url).href);
  const client = new PGlite({extensions:{pgcrypto}});
  const sql = async statement => {
    const result = await client.exec('reset role; set request.headers = \'{"x-pool-regular-schema":"20261009"}\';\n' + statement);
    const row = result.at(-1)?.rows[0];
    if (!row) return '';
    const [value] = Object.values(row);
    return value && typeof value === 'object' ? JSON.stringify(value) : String(value ?? '');
  };
  try {
    await prepareQbFixture(sql, randomBytes(32).toString('hex'));
    return await task(sql);
  } finally {
    await client.close();
  }
}

async function business(sql) {
  return queryJson(sql, `select jsonb_build_object(
    'week',public.regular_week_ranking_state(2026,5),
    'scores',coalesce((select jsonb_agg(to_jsonb(t) order by season,week,user_id) from public.weekly_scores t),'[]'),
    'versions',coalesce((select jsonb_agg(to_jsonb(t) order by season,week) from public.regular_ranking_versions t),'[]'),
    'clocks',coalesce((select jsonb_agg(to_jsonb(t) order by season,week) from public.qb_selection_weeks t),'[]'),
    'catalogue',(select jsonb_agg(to_jsonb(t) order by id) from public.qbs t),
    'reservations',coalesce((select jsonb_agg(to_jsonb(t) order by season,week,team_id) from qb_observation.regular_menu_reservations t),'[]'),
    'team_standings',(select jsonb_agg(to_jsonb(t) order by id) from public.teams t),
    'qb_stats',coalesce((select jsonb_agg(to_jsonb(t) order by season,week,espn_athlete_id) from public.qb_weekly_stats t),'[]'),
    'events',coalesce((select jsonb_agg(to_jsonb(t)-'qb_final_payload'-'qb_final_attempted_at' order by event_key) from public.push_notification_events t),'[]')
  );`);
}

